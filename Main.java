/**
 * صنف التشغيل الرئيسي Main
 * ينفّذ المهام الـ 12 المطلوبة بالترتيب مع إظهار التعليقات التوضيحية لكل خطوة.
 */
public class Main {

    public static void main(String[] args) {
        // الحصول على الكائنات الفريدة عبر نمط Singleton
        AccountRepository repository = AccountRepository.getInstance(); // استدعاء المستودع
        AuditLogger logger = AuditLogger.getInstance();                 // استدعاء سجل التدقيق

        
        System.out.println("      بدء تنفيذ قائمة المهام المطلوبة (TP1)       ");
        System.out.println("==================================================\n");

        // -----------------------------------------------------------------
        // [المهمة 1]: إنشاء حسابين لطالبين داخل الدالة main باستخدام نمط Builder
        // -----------------------------------------------------------------
        System.out.println("--- [المهمة 1] إنشاء حسابين لطالبين ---");
        
        // بناء حساب الطالب الأول (أحمد علي)
        StudentAccount student1 = new StudentAccount.Builder("20260001", "أحمد علي", "ahmed.ali@univ.dz")
                .major("Informatique") // التخصص
                .level("L3")           // المستوى
                .build();              // إنشاء الكائن النهائى

        // بناء حساب الطالب الثاني (مريم خالد)
        StudentAccount student2 = new StudentAccount.Builder("20260002", "مريم خالد", "meryem.k@univ.dz")
                .major("Mathématiques") // التخصص
                .level("M1")            // المستوى
                .build();               // إنشاء الكائن النهائي

        System.out.println("تم إنشاء كائنات الطالبين بنجاح في الذاكرة.\n");

        // -----------------------------------------------------------------
        // [المهام 2، 3، 4]: تنفيذ إضافة الحساب الأول، الحساب الثاني، وتأكيد النجاح
        // -----------------------------------------------------------------
        System.out.println("--- [المهام 2، 3، 4] تنفيذ الإضافة وعرض رسائل النجاح ---");
        
        repository.addAccount(student1); // تنفيذ عملية إضافة الحساب الأول (المهمة 2)
        repository.addAccount(student2); // تنفيذ عملية إضافة الحساب الثاني (المهمة 3)
        
        System.out.println("✔️ تم إظهار وتأكيد رسائل نجاح الإضافة أعلاه عبر AuditLogger.\n"); // (المهمة 4)

        // -----------------------------------------------------------------
        // [المهام 5، 6]: حذف الحساب الأول ثم الحساب الثاني
        // -----------------------------------------------------------------
        System.out.println("--- [المهام 5، 6] حذف الحساب الأول والثاني ---");
        
        repository.removeAccount("20260001"); // حذف الحساب الأول (المهمة 5)
        repository.removeAccount("20260002"); // حذف الحساب الثاني (المهمة 6)
        System.out.println();

        // -----------------------------------------------------------------
        // [المهمة 7]: إعادة تنفيذ عملية الإضافة مرتين، مع تسجيل كل عملية
        // -----------------------------------------------------------------
        System.out.println("--- [المهمة 7] إعادة تنفيذ عملية الإضافة مرتين وتسجيلهما ---");
        
        repository.addAccount(student1); // إعادة إدخال الطالب الأول والتسجيل تلقائياً
        repository.addAccount(student2); // إعادة إدخال الطالب الثاني والتسجيل تلقائياً
        System.out.println();

        // -----------------------------------------------------------------
        // [المهمة 8]: إعادة تنفيذ عملية الحذف مرتين، مع تسجيل كل عملية
        // -----------------------------------------------------------------
        System.out.println("--- [المهمة 8] إعادة تنفيذ عملية الحذف مرتين وتسجيلهما ---");
        
        repository.removeAccount("20260001"); // إعادة حذف الطالب الأول والتسجيل تلقائياً
        repository.removeAccount("20260002"); // إعادة حذف الطالب الثاني والتسجيل تلقائياً
        System.out.println();

        // -----------------------------------------------------------------
        // [المهام 9، 10]: محاولة حذف حساب غير موجود وإظهار رسالة خطأ ERROR
        // -----------------------------------------------------------------
        System.out.println("--- [المهام 9، 10] محاولة حذف حساب غير موجود ورسالة الخطأ ---");
        
        // التوجيه بحذف رقم غير مسجل للتأكد من التقاط الخطأ (المهمة 9)
        repository.removeAccount("99999999"); // سيتم إصدار رسالة ERROR موضحة (المهمة 10)
        System.out.println();

        // -----------------------------------------------------------------
        // [المهام 11، 12]: عرض سجل العمليات التاريخي الشامل وتفقده
        // -----------------------------------------------------------------
        System.out.println("--- [المهام 11، 12] عرض سجل العمليات التاريخي (Historique des opérations) ---");
        
        // عرض السجل الذي يحتفظ بكافة الأحداث الناجحة والفاشلة بترتيبها الزمني (المهام 11 و 12)
        logger.printHistory();
    }
}
